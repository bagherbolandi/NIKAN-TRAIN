const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
(async()=>{
 const browser=await chromium.launch({headless:true,channel:'msedge'});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:18876');
 await page.locator('#auth [name=username]').fill('admin');await page.locator('#auth [name=password]').fill('test-password-12345');await page.locator('#auth button').click();
 await page.locator('[data-page=governance]').click();
 await page.locator('#holding-year').fill('1405');await page.locator('#holding-refresh').click();
 await page.locator('[data-decide=approved]').first().waitFor();
 await page.screenshot({path:'qa-holding.png',fullPage:true});
 page.once('dialog',dialog=>dialog.accept('تصویب بر اساس بررسی گپ مهارتی'));
 await page.locator('[data-decide=approved]').first().click();
 await page.locator('[data-decide=submitted]').first().waitFor();
 await page.locator('[data-plan]').first().click();
 await page.locator('#entry [name=objective]').fill('افزایش توانایی کاربرد مهارت');
 for(const [k,v] of Object.entries({method:'آموزش عملی',owner:'مدیر آموزش',due_date:'1405/12/01',success_criterion:'نمره عملی حداقل ۸۰ از ۱۰۰',baseline:'30',target:'80'}))await page.locator('#entry [name='+k+']').fill(v);
 await page.locator('#entry button[type=submit],#entry > button').last().click();
 await page.locator('#dialog').waitFor({state:'hidden'});
 await page.getByText('افزایش توانایی کاربرد مهارت',{exact:false}).first().waitFor();
 await page.screenshot({path:'qa-holding-approved.png',fullPage:true});
 await page.locator('#logout').click();
 await page.locator('#auth [name=username]').fill('manager');await page.locator('#auth [name=password]').fill('test-password-12345');await page.locator('#auth button').click();
 await page.locator('#shell').waitFor({state:'visible'});
 if(await page.locator('[data-page=governance]').count())throw Error('Holding desk exposed to company navigation');
 await page.locator('[data-page=needs]').click();
 await page.screenshot({path:'qa-company.png',fullPage:true});
 if(errors.length)throw Error(errors.join('\n'));
 await browser.close();console.log('Browser workflow passed: login, holding review, approval, plan, company isolation; no JS errors.');
})().catch(e=>{console.error(e);process.exit(1)});
